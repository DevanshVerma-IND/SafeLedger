"""
Page 6: Benchmark & Performance
Integrates benchmark.py and reads results/benchmark.csv, results/sweep.csv, and results/benchmark.png.
Provides execution trigger for quick/full benchmark runs.
"""
import os, time
import pandas as pd
import streamlit as st
import benchmark
from ui.styles import render_header, render_metric

MODES = ["naive", "wfg", "ordered", "banker", "wfg+ml", "banker+ml"]

def render_page(pred, model_path):
    render_header(
        "Empirical Benchmark & System Profiling",
        "Comparative evaluation across all 6 concurrency configurations, client worker sweeps, and cloud server cost modeling.",
        badge="Performance Profiling"
    )

    bench_csv = "results/benchmark.csv"
    sweep_csv = "results/sweep.csv"
    bench_png = "results/benchmark.png"

    has_bench = os.path.exists(bench_csv)
    has_sweep = os.path.exists(sweep_csv)

    # Benchmark Execution Panel
    with st.expander("Benchmark Execution Controls", expanded=not has_bench):
        st.write("Execute systematic benchmarks across all 6 concurrency control configurations over 5 distinct held-out workload seeds.")
        st.caption("Note: Quick benchmark evaluates 2 seeds (~30 seconds); Full benchmark evaluates 5 seeds plus concurrency sweep (~2-3 minutes).")
        
        b1, b2 = st.columns(2)
        run_quick = b1.button("Run Quick Benchmark (2 Seeds)")
        run_full = b2.button("Run Full Benchmark Suite (5 Seeds + Sweep)")

        if run_quick or run_full:
            with st.spinner("Executing benchmark suites via engine.py and benchmark.py..."):
                t0 = time.perf_counter()
                benchmark.main(quick=run_quick)
                elapsed = time.perf_counter() - t0
            st.success(f"Benchmark run completed in {elapsed:.1f} seconds. Results saved to `results/`.")
            st.rerun()

    if not has_bench:
        st.warning("No benchmark dataset found in `results/benchmark.csv`. Use the buttons above or run `python benchmark.py` in your shell.")
        return

    df_bench = pd.read_csv(bench_csv)

    # Aggregated KPI Cards
    st.markdown("#### Performance Summary (16 Clients, 300 Transactions)")
    summary_cols = ["tps", "p50_ms", "p95_ms", "retries", "deadlocks", "timeouts", "banker_waits", "cpu_ms_per_txn"]
    valid_cols = [c for c in summary_cols if c in df_bench.columns]
    agg_df = df_bench.groupby("mode")[valid_cols].mean().round(2)

    # Order rows according to standard MODES list
    ordered_indices = [m for m in MODES if m in agg_df.index]
    agg_df = agg_df.loc[ordered_indices]

    st.dataframe(agg_df, width='stretch')

    # Visualizations
    st.markdown("#### Comparative Strategy Metrics")
    c1, c2 = st.columns(2)
    with c1:
        st.markdown("**Throughput (Transactions/Sec) — Higher is Better**")
        st.bar_chart(agg_df[["tps"]])
    with c2:
        st.markdown("**P95 Tail Latency (Milliseconds) — Lower is Better**")
        st.bar_chart(agg_df[["p95_ms"]])

    c3, c4 = st.columns(2)
    with c3:
        st.markdown("**Retries & Deadlocks — Lower is Better**")
        st.bar_chart(agg_df[["retries", "deadlocks"]])
    with c4:
        st.markdown("**CPU Utilization (ms per Transaction)**")
        st.bar_chart(agg_df[["cpu_ms_per_txn"]])

    # Concurrency Sweep if available
    if has_sweep:
        st.markdown("---")
        st.markdown("#### Concurrency Scalability Sweep (Throughput vs. Worker Threads)")
        df_sweep = pd.read_csv(sweep_csv)
        if "workers" in df_sweep.columns and "tps" in df_sweep.columns:
            sweep_pivot = df_sweep.groupby(["workers", "mode"])["tps"].mean().unstack()
            st.line_chart(sweep_pivot)
            st.caption("Illustrates horizontal scalability and thrashing limits under high thread contention (4 to 32 worker threads).")

    # Cost Model
    st.markdown("---")
    st.markdown("#### Cloud Deployment Cost Projection")
    st.write("Estimates cloud compute cost per 1,000,000 transactions based on measured system throughput:")

    price = st.number_input("Cloud Compute Price ($ / Hour)", min_value=0.01, max_value=50.0, value=0.10, step=0.02)
    
    cost_df = agg_df[["tps", "cpu_ms_per_txn"]].copy()
    cost_df["USD / 1M Txns"] = (price * 1e6 / (cost_df["tps"] * 3600)).round(3)
    cost_df["CPU-Hours / 1M Txns"] = (cost_df["cpu_ms_per_txn"] * 1e6 / 3.6e6).round(3)
    
    st.dataframe(cost_df[["tps", "cpu_ms_per_txn", "USD / 1M Txns", "CPU-Hours / 1M Txns"]], width='stretch')
    st.caption("Calculations derived from measured machine execution metrics. Production network latencies may adjust totals.")

    # Show official benchmark chart if generated
    if os.path.exists(bench_png):
        with st.expander("View Matplotlib Benchmark Publication Figure", expanded=False):
            st.image(bench_png, caption="Generated by benchmark.py plot() routine", width='stretch')
